set -euo pipefail

if [ -d "venvp3" ]; then
  source venvp3/bin/activate
fi

echo "[$(date)] ==================== Cleaning up resources... ===================="
# [START hypercomputer_tpu_tune_qwen3_30b_rl_cleanup]

# Strip random hex suffix to get base pattern
BASE_CLUSTER_NAME=$(echo "${CLUSTER_NAME}" | sed -E 's/-[a-f0-9]{4}$//')

# 1. Discover ALL clusters generated by this run (including retry attempts)
CLUSTERS_TO_DELETE=()
while IFS= read -r line; do
  [ -n "$line" ] && CLUSTERS_TO_DELETE+=("$line")
done < <(gcloud container clusters list --project="${PROJECT}" --location="${REGION}" --filter="name~'^${BASE_CLUSTER_NAME}'" --format="value(name)" 2>/dev/null || true)

if [ ${#CLUSTERS_TO_DELETE[@]} -gt 0 ]; then
  for TARGET_CLUSTER in "${CLUSTERS_TO_DELETE[@]}"; do
    echo "Processing teardown for cluster: ${TARGET_CLUSTER}..."

    # 1a. Delete active workloads and JobSets
    xpk workload delete --workload "qwen-hf-to-mt" --cluster "${TARGET_CLUSTER}" --project="${PROJECT}" --zone="${ZONE}" 2>/dev/null || true
    xpk workload delete --workload "qwen-training" --cluster "${TARGET_CLUSTER}" --project="${PROJECT}" --zone="${ZONE}" 2>/dev/null || true
    xpk workload delete --workload "qwen-mt-to-hf" --cluster "${TARGET_CLUSTER}" --project="${PROJECT}" --zone="${ZONE}" 2>/dev/null || true

    # 1b. Delete GKE cluster FIRST to stop MIG auto-healing from recreating TPU VMs
    echo "Deleting GKE cluster ${TARGET_CLUSTER}..."
    xpk cluster delete --cluster "${TARGET_CLUSTER}" --project "${PROJECT}" --zone "${ZONE}" --force 2>/dev/null || \
      gcloud container clusters delete "${TARGET_CLUSTER}" --location="${REGION}" --project="${PROJECT}" --quiet --async 2>/dev/null || true
  done
else
  echo "No active GKE clusters found matching ${BASE_CLUSTER_NAME}."
fi

# 2. Terminate any residual orphan TPU/CPU VM instances
echo "Terminating residual VM instances attached to ${BASE_CLUSTER_NAME}..."
gcloud compute instances list \
  --project="${PROJECT}" \
  --zones="${ZONE}" \
  --filter="labels.goog-k8s-cluster-name~'^${BASE_CLUSTER_NAME}' OR name~'^gke-${BASE_CLUSTER_NAME}'" \
  --format="value(name,zone)" 2>/dev/null | while read -r name zone; do
    if [ -n "$name" ]; then
      echo " -> Deleting orphan instance: $name ($zone)"
      gcloud compute instances delete "$name" --zone="$zone" --project="${PROJECT}" --quiet 2>/dev/null || true
    fi
done

# 3. Clean up Pathways ANP networking stack (Firewalls -> Subnets -> VPCs)
RUN_HASH=$(echo "${BASE_CLUSTER_NAME}" | sed -E 's/pkb-//; s/-cluster//')

if [ -n "$RUN_HASH" ]; then
  echo "Cleaning up ANP networking stack for run hash: ${RUN_HASH}..."

  # 3a. Delete firewall rules
  gcloud compute firewall-rules list \
    --project="${PROJECT}" \
    --filter="network~'gke-anp.*${RUN_HASH}'" \
    --format="value(name)" 2>/dev/null | while read -r fw; do
      [ -n "$fw" ] && gcloud compute firewall-rules delete "$fw" --project="${PROJECT}" --quiet 2>/dev/null || true
  done

  sleep 5

  # 3b. Delete subnetworks
  gcloud compute networks subnets list \
    --project="${PROJECT}" \
    --regions="${REGION}" \
    --filter="name~'gke-anp.*${RUN_HASH}'" \
    --format="value(name)" 2>/dev/null | while read -r subnet; do
      [ -n "$subnet" ] && gcloud compute networks subnets delete "$subnet" --region="${REGION}" --project="${PROJECT}" --quiet 2>/dev/null || true
  done

  # 3c. Delete VPC networks
  gcloud compute networks list \
    --project="${PROJECT}" \
    --filter="name~'gke-anp.*${RUN_HASH}'" \
    --format="value(name)" 2>/dev/null | while read -r net; do
      [ -n "$net" ] && gcloud compute networks delete "$net" --project="${PROJECT}" --quiet 2>/dev/null || true
  done
fi

# 4. Delete Cloud Storage bucket and Artifact Registry repository
echo "Cleaning up Cloud Storage bucket and Artifact Registry repository..."
gcloud storage rm --recursive "gs://${GCS_BUCKET}" 2>/dev/null || echo "Warning: Failed to delete bucket gs://${GCS_BUCKET}"
gcloud artifacts repositories delete maxtext-images --location="${REGION}" --project="${PROJECT}" --quiet 2>/dev/null || echo "Warning: Failed to delete repository maxtext-images"

# [END hypercomputer_tpu_tune_qwen3_30b_rl_cleanup]
echo "[$(date)] ==================== Resources cleaned up. ===================="
