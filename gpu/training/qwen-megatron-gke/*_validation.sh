set -euo pipefail

echo "=== 1. Validating Cloud Storage dataset and checkpoints ==="
TRAINING_BUCKET="$(kubectl get pv -o jsonpath='{.items[?(@.spec.storageClassName=="gcsfusecsi-training")].spec.csi.volumeHandle}')"
CHECKPOINT_BUCKET="$(kubectl get pv -o jsonpath='{.items[?(@.spec.storageClassName=="gcsfusecsi-checkpointing")].spec.csi.volumeHandle}')"

if [[ -z "${TRAINING_BUCKET}" || -z "${CHECKPOINT_BUCKET}" ]]; then
  echo "Validation failed: could not resolve TRAINING_BUCKET or CHECKPOINT_BUCKET from cluster PVs." >&2
  exit 1
fi

for path in \
  "gs://${TRAINING_BUCKET}/dataset/c4_qwen3_text_document.bin" \
  "gs://${TRAINING_BUCKET}/dataset/c4_qwen3_text_document.idx" \
  "gs://${TRAINING_BUCKET}/tokenizer/tokenizer.json" \
  "gs://${CHECKPOINT_BUCKET}/qwen3-30b-a3b/latest_checkpointed_iteration.txt"; do
  if ! gcloud storage ls "${path}" >/dev/null 2>&1; then
    echo "Validation failed: expected object not found: ${path}" >&2
    exit 1
  fi
done

for iter_dir in iter_0000025 iter_0000050; do
  shard_count=$( (gcloud storage ls "gs://${CHECKPOINT_BUCKET}/qwen3-30b-a3b/${iter_dir}/*.distcp" 2>/dev/null || true) | wc -l | tr -d ' ')
  if [ "${shard_count}" -lt 1 ]; then
    echo "Validation failed: no .distcp shards found in gs://${CHECKPOINT_BUCKET}/qwen3-30b-a3b/${iter_dir}/" >&2
    exit 1
  fi
  echo "Verified ${iter_dir}: ${shard_count} .distcp shards present."
done

LATEST_ITER=$(gcloud storage cat "gs://${CHECKPOINT_BUCKET}/qwen3-30b-a3b/latest_checkpointed_iteration.txt" | tr -d '[:space:]')
if [ "${LATEST_ITER}" != "55" ]; then
  echo "Validation failed: expected latest_checkpointed_iteration.txt to be 55, got '${LATEST_ITER}'." >&2
  exit 1
fi
echo "Verified latest_checkpointed_iteration.txt = ${LATEST_ITER}."

echo "=== 2. Validating Run 1 (iterations 1-50) captured logs ==="
if [[ ! -s pretrain_run1_node0.log || ! -s pretrain_run1_node1.log ]]; then
  echo "Validation failed: pretrain_run1_node0.log and pretrain_run1_node1.log are required (generated by 3_pretrain.sh)." >&2
  exit 1
fi

if ! grep -q "Sourcing /etc/gcp_nccl_init.sh" pretrain_run1_node0.log; then
  echo "Validation failed: /etc/gcp_nccl_init.sh was not sourced in Run 1 Node 0 logs." >&2
  exit 1
fi

if ! grep -q "scheduled an async" pretrain_run1_node0.log || ! grep -q "successfully saved" pretrain_run1_node0.log; then
  echo "Validation failed: mid-run async checkpoint schedule/save messages missing in Run 1 Node 0 logs." >&2
  exit 1
fi

if ! grep -Eq "iteration +25/" pretrain_run1_node1.log || ! grep -Eq "iteration +50/" pretrain_run1_node1.log; then
  echo "Validation failed: expected iterations 25 and 50 in Run 1 Node 1 logs." >&2
  exit 1
fi

python3 - pretrain_run1_node1.log <<'PYEOF'
import math
import re
import sys

log_path = sys.argv[1]
with open(log_path, "r", encoding="utf-8", errors="replace") as f:
    text = f.read()

pattern = re.compile(r"iteration\s+(\d+)/\s*\d+.*?lm loss:\s*([0-9eE.+\-nanNaNinfInf]+)")
losses = {}
for m in pattern.finditer(text):
    step = int(m.group(1))
    val_str = m.group(2)
    try:
        val = float(val_str)
    except ValueError:
        print(f"Validation failed: non-numeric lm loss '{val_str}' at iteration {step}", file=sys.stderr)
        sys.exit(1)
    if not math.isfinite(val):
        print(f"Validation failed: non-finite lm loss ({val}) at iteration {step}", file=sys.stderr)
        sys.exit(1)
    losses[step] = val

if 1 not in losses or 50 not in losses:
    print(f"Validation failed: missing iteration 1 or 50 loss in Run 1 logs (found steps: {sorted(losses)[:5]} ... {sorted(losses)[-5:]})", file=sys.stderr)
    sys.exit(1)

if losses[50] >= losses[1]:
    print(f"Validation failed: lm loss did not decrease (iter 1: {losses[1]:.4f}, iter 50: {losses[50]:.4f})", file=sys.stderr)
    sys.exit(1)

print(f"Verified Run 1 loss convergence: iter 1 = {losses[1]:.4f} -> iter 50 = {losses[50]:.4f} (0 NaN/Inf across {len(losses)} logged steps).")
PYEOF

echo "=== 3. Validating resumed JobSet (iterations 50 -> 55) ==="
JOBSET_COMPLETED=$(kubectl get jobset qwen3-30b-a3b -o jsonpath='{.status.conditions[?(@.type=="Completed")].status}' 2>/dev/null || true)
if [ "${JOBSET_COMPLETED}" != "True" ]; then
  echo "Validation failed: resumed jobset/qwen3-30b-a3b is not in Completed state." >&2
  kubectl describe jobset qwen3-30b-a3b >&2 || true
  exit 1
fi

RESUME_NODE0_LOGS=$(kubectl logs --tail=-1 \
  -l jobset.sigs.k8s.io/jobset-name=qwen3-30b-a3b,batch.kubernetes.io/job-completion-index=0 \
  -c megatron-bridge)
RESUME_NODE1_LOGS=$(kubectl logs --tail=-1 \
  -l jobset.sigs.k8s.io/jobset-name=qwen3-30b-a3b,batch.kubernetes.io/job-completion-index=1 \
  -c megatron-bridge)

if ! echo "${RESUME_NODE0_LOGS}" | grep -Eq "successfully loaded checkpoint.*at iteration 50"; then
  echo "Validation failed: did not observe clean checkpoint load at iteration 50 in resumed Node 0 logs." >&2
  exit 1
fi

for step in 51 52 53 54 55; do
  if ! echo "${RESUME_NODE1_LOGS}" | grep -Eq "iteration +${step}/"; then
    echo "Validation failed: iteration ${step} missing from resumed Node 1 logs." >&2
    exit 1
  fi
done

echo "${RESUME_NODE1_LOGS}" | python3 - <<'PYEOF'
import math
import re
import sys

text = sys.stdin.read()
pattern = re.compile(r"iteration\s+(\d+)/\s*\d+.*?lm loss:\s*([0-9eE.+\-nanNaNinfInf]+)")
losses = {}
for m in pattern.finditer(text):
    step = int(m.group(1))
    val = float(m.group(2))
    if not math.isfinite(val):
        print(f"Validation failed: non-finite lm loss ({val}) at resumed iteration {step}", file=sys.stderr)
        sys.exit(1)
    losses[step] = val

for step in (51, 52, 53, 54, 55):
    if step not in losses:
        print(f"Validation failed: missing lm loss for resumed iteration {step}", file=sys.stderr)
        sys.exit(1)

print(f"Verified resumed iterations 51-55: iter 51 = {losses[51]:.4f} -> iter 55 = {losses[55]:.4f} (0 NaN/Inf).")
PYEOF

echo "Validation passed: C4 dataset, mid-run async checkpointing (iter 25 & 50), loss convergence, and clean resume (iter 50 -> 55) all verified."
